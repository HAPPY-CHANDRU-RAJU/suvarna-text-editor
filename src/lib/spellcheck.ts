export type SupportedLanguage = 'kannada';

const dictionaries: Record<SupportedLanguage, Set<string>> = {
  kannada: kannadaDictionary,
};

export function getDictionary(lang: SupportedLanguage): Set<string> {
  return dictionaries[lang];
}

// Simple Levenshtein distance
function levenshtein(a: string, b: string): number {
  const m = a.length, n = b.length;
  const dp: number[][] = Array.from({ length: m + 1 }, () => Array(n + 1).fill(0));
  for (let i = 0; i <= m; i++) dp[i][0] = i;
  for (let j = 0; j <= n; j++) dp[0][j] = j;
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      dp[i][j] = a[i - 1] === b[j - 1]
        ? dp[i - 1][j - 1]
        : 1 + Math.min(dp[i - 1][j], dp[i][j - 1], dp[i - 1][j - 1]);
    }
  }
  return dp[m][n];
}

export function checkSpelling(word: string, lang: SupportedLanguage): boolean {
  return getDictionary(lang).has(word);
}

export function getSuggestions(word: string, lang: SupportedLanguage, maxResults = 5): string[] {
  const dict = getDictionary(lang);
  const scored: { word: string; dist: number }[] = [];
  
  for (const dictWord of dict) {
    const dist = levenshtein(word, dictWord);
    if (dist <= 3) {
      scored.push({ word: dictWord, dist });
    }
  }
  
  scored.sort((a, b) => a.dist - b.dist);
  return scored.slice(0, maxResults).map(s => s.word);
}

// Detect which language a word likely belongs to based on Unicode ranges
export function detectLanguage(text: string): SupportedLanguage {
  return 'kannada'; // Only support Kannada
}

// Tokenize text into words
export function tokenize(text: string): { word: string; start: number; end: number }[] {
  const tokens: { word: string; start: number; end: number }[] = [];
  const regex = /[\u0900-\u0D7F]+/g;
  let match;
  while ((match = regex.exec(text)) !== null) {
    tokens.push({ word: match[0], start: match.index, end: match.index + match[0].length });
  }
  return tokens;
}

export interface SpellError {
  word: string;
  start: number;
  end: number;
  suggestions: string[];
  language: SupportedLanguage;
}

export function spellCheck(text: string): SpellError[] {
  const tokens = tokenize(text);
  const errors: SpellError[] = [];
  
  for (const token of tokens) {
    const lang = detectLanguage(token.word);
    if (!checkSpelling(token.word, lang)) {
      const suggestions = getSuggestions(token.word, lang);
      if (suggestions.length > 0) {
        errors.push({
          word: token.word,
          start: token.start,
          end: token.end,
          suggestions,
          language: lang,
        });
      }
    }
  }
  
  return errors;
}
